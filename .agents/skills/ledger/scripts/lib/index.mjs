// index.mjs — reads hand-offs, archive digests and memory, regenerates the index files (per
// project and at the root), and selects what is relevant to a piece of text. Selection is
// keyword scoring, deterministic and cheap: Claude reads the result, never the whole folders.
// Scope is strictly one project; "elsewhere" counts only tell Claude other projects have hits.

import fs from 'node:fs';
import path from 'node:path';
import { parseFrontmatter } from './fm.mjs';
import { legacyContent, listProjects } from './projects.mjs';
import { paths, readJson, rel, safeList } from './repo.mjs';

const GENERATED_MARK = '<!-- generated by ledger: rebuilt on every run, do not edit -->';
const MEMORY_KINDS = ['preferences', 'facts', 'lessons'];
const PROJECT_MEMORY_KINDS = ['facts', 'lessons'];
const STOP = new Set(
	(
		'the a an and or but if then of to in on at for from by with without about into over under as is are was were be been ' +
		'being have has had do does did will would should could can may might must this that these those it its we our us you ' +
		'your they their them he she his her i me my not no yes so than too very just also only all any each both more most ' +
		'other some such new one two three first last next now here there when where why how what which who whom while because ' +
		'after before during until since again further once same own same per via use used using make made need needs want ' +
		'wants like get got set put let say says said see seen know knows think thought go going gone come came'
	).split(/\s+/),
);
// Chinese, Japanese and Korean put no spaces between words, so a run of their characters is cut
// into overlapping two-character pieces (bigrams), the usual dictionary-free way to search them:
// "示例科技" gives 示例, 例科, 科技, and a text holding the phrase matches all three. A bigram made of
// two Chinese function characters (我们, 他们) or listed as a stop word carries no subject and is
// always dropped. Outside find (whole documents, and check/run topics), a bigram with one function
// character inside a longer run is dropped too; a two-character word (在线, 目的) is always kept.
const CJK = '\\p{Script=Han}\\p{Script=Hiragana}\\p{Script=Katakana}\\p{Script=Hangul}\\u30fc';
const CJK_STOP_CHARS = new Set([...'的了和与及或是在于也就都而把被着吗呢吧啊之其这那们我你他她它']);
const CJK_STOP = new Set(
	'关于 可以 进行 通过 如果 因为 所以 已经 一个 没有 什么 需要 目前 这个 那个 这些 那些 这样 那样 其中 以及 或者 但是 还是 而且 并且 因此 由于 对于'.split(' '),
);
const CJK_START = new RegExp(`^[${CJK}]`, 'u');
const NB = `(?:(?![${CJK}])[\\p{L}\\p{N}])`; // a letter or digit that is not CJK: Chinese sits right against ids and numbers
// One token per match: a CJK run (1); an id, date, amount or version kept whole for a search (2:
// 2026年3月15日, H-017, 2026-03-15, 1234.5678, v1.5); a word of any other script (3).
const TOKEN = new RegExp(
	`([${CJK}]+)` +
		`|(\\d{4}年\\d{1,2}月(?:\\d{1,2}[日号])?|\\d{1,2}月\\d{1,2}[日号]` +
		`|(?<!${NB})(?:(?![${CJK}])\\p{L}){1,3}-\\d+(?!${NB})` +
		`|\\d{4}-\\d{2}(?:-\\d{2})?` +
		`|(?<!${NB})v?\\d+(?:[.,]\\d+)+)` +
		`|(${NB}+)`,
	'gu',
);
// Keywords of a whole document keep none of those: they are noise there, and leaving them out
// keeps English keywords exactly as they were before CJK support.
const TOKEN_LOOSE = new RegExp(`([${CJK}]+)|()(${NB}+)`, 'gu');
const ID_WORD = /^\p{L}{1,3}-\d+$/u;

/** Text as it is compared: NFKC (PDF extraction can yield ⽣ for 生, and full-width ＡＢＣ) and lower case. */
const fold = (t) => String(t ?? '').normalize('NFKC').toLowerCase();

const list = (v) => (Array.isArray(v) ? v : v ? [String(v)] : []);

// ---------------------------------------------------------------- loading

/** Hand-offs of one scope: a project slug, or null for the root (pre-project content). */
export function loadHandoffs(root, project = null) {
	const dir = paths(root, project).handoffs;
	return safeList(dir)
		.filter((f) => /^H-\d+.*\.md$/.test(f))
		.map((f) => {
			const file = path.join(dir, f);
			const { data, body } = parseFrontmatter(fs.readFileSync(file, 'utf8'));
			return { file, relFile: rel(root, file), project, data: normalizeHandoff(data, f, project), body };
		})
		.sort((a, b) => a.data.id.localeCompare(b.data.id));
}

export function loadAllHandoffs(root) {
	return [...listProjects(root).flatMap((p) => loadHandoffs(root, p.slug)), ...loadHandoffs(root, null)].sort((a, b) => a.data.id.localeCompare(b.data.id));
}

function normalizeHandoff(data, filename, project) {
	return {
		...data,
		id: data.id || filename.match(/^(H-\d+)/)[1],
		title: data.title || filename.replace(/\.md$/, ''),
		date: data.date || '',
		project: data.project || project || null,
		topics: list(data.topics).map((t) => String(t).toLowerCase()),
		status: data.status || 'final',
		superseded_by: data.superseded_by || null,
		supersedes: list(data.supersedes),
		summary: data.summary || '',
		decisions: list(data.decisions),
	};
}

/** Archive digests of one scope: <archive>/<group>/A-NNN-<slug>.md, one per old document. */
export function loadArchive(root, project = null) {
	const dir = paths(root, project).archive;
	const out = [];
	for (const group of safeList(dir)) {
		if (group.startsWith('.') || group === 'inbox') continue;
		const gdir = path.join(dir, group);
		if (!fs.statSync(gdir).isDirectory()) continue;
		for (const f of safeList(gdir).filter((f) => /^A-\d+.*\.md$/.test(f))) {
			const file = path.join(gdir, f);
			const { data, body } = parseFrontmatter(fs.readFileSync(file, 'utf8'));
			out.push({ file, relFile: rel(root, file), project, group, data: normalizeArchive(data, f, group, project), body });
		}
	}
	return out.sort((a, b) => a.data.id.localeCompare(b.data.id));
}

export function loadAllArchive(root) {
	return [...listProjects(root).flatMap((p) => loadArchive(root, p.slug)), ...loadArchive(root, null)].sort((a, b) => a.data.id.localeCompare(b.data.id));
}

function normalizeArchive(data, filename, group, project) {
	return {
		...data,
		id: data.id || filename.match(/^(A-\d+)/)[1],
		title: data.title || filename.replace(/\.md$/, ''),
		kind: data.kind || 'other',
		date: data.date || '',
		date_confidence: data.date_confidence || 'low',
		project: data.project || project || null,
		group: data.group || group,
		topics: list(data.topics).map((t) => String(t).toLowerCase()),
		status: data.status || 'active',
		superseded_by: data.superseded_by || null,
		supersedes: list(data.supersedes),
		summary: data.summary || '',
		decisions: list(data.decisions),
		source: data.source || '',
		source_text: data.source_text || '',
	};
}

function readMemoryDir(root, dir, kind, scope) {
	return safeList(dir)
		.filter((f) => f.endsWith('.md'))
		.map((f) => {
			const file = path.join(dir, f);
			const { data, body } = parseFrontmatter(fs.readFileSync(file, 'utf8'));
			return {
				kind,
				scope,
				file,
				relFile: rel(root, file),
				name: data.name || f.replace(/\.md$/, ''),
				topics: list(data.topics).map((t) => String(t).toLowerCase()),
				date: data.date || '',
				source: data.source || '',
				body: body.trim(),
			};
		});
}

/** Global memory (preferences, facts, lessons) plus, with a project, that project's facts and lessons. */
export function loadMemory(root, project = null) {
	const p = paths(root, project);
	const out = MEMORY_KINDS.flatMap((kind) => readMemoryDir(root, path.join(p.globalMemory, kind), kind, 'global'));
	if (project) out.push(...PROJECT_MEMORY_KINDS.flatMap((kind) => readMemoryDir(root, path.join(p.memory, kind), kind, 'project')));
	return out;
}

/** Archive group names, from the global state file: groups[project][slug] (legacy flat form = root scope). */
function readGroups(root, project) {
	const state = readJson(paths(root).archiveState, {});
	const g = state.groups || {};
	const flat = Object.values(g).some((v) => v && typeof v.name === 'string');
	if (flat) return project ? {} : g;
	return g[project || ''] || {};
}

// ---------------------------------------------------------------- writing

function cell(v) {
	return String(v ?? '').replace(/\|/g, '/').replace(/\s+/g, ' ').trim();
}

function stateOf(entry, activeWord = 'active') {
	return entry.data.status === 'superseded' ? `superseded by ${entry.data.superseded_by || '?'}` : activeWord;
}

function scopeLabel(project) {
	return project ? `project ${project.name} (${project.slug})` : 'not yet in a project';
}

function writeHandoffIndex(p, handoffs, project) {
	const rows = [...handoffs].reverse().map((h) => {
		const status = h.data.status === 'superseded' ? `superseded by ${h.data.superseded_by || '?'}` : h.data.status;
		return `| ${h.data.id} | ${h.data.date} | [${cell(h.data.title)}](${path.basename(h.file)}) | ${h.data.topics.join(', ')} | ${status} | ${h.data.decisions.length} | ${cell(h.data.summary)} |`;
	});
	fs.mkdirSync(p.handoffs, { recursive: true });
	fs.writeFileSync(
		path.join(p.handoffs, 'INDEX.md'),
		[
			`# Hand-offs — ${scopeLabel(project)}`,
			GENERATED_MARK,
			'',
			`Hand-offs: ${handoffs.length}, newest first. Decisions are listed in ../memory/DECISIONS.md; older material in ../archive/INDEX.md.`,
			'',
			'| Id | Date | Title | Topics | Status | Decisions | Summary |',
			'|---|---|---|---|---|---|---|',
			...rows,
			'',
		].join('\n'),
	);
}

/** archive/INDEX.md: one section per group, newest first inside it, version chains visible. */
function writeArchiveIndex(p, archive, groups, project) {
	if (!fs.existsSync(p.archive)) return;
	const byGroup = new Map();
	for (const a of archive) byGroup.set(a.group, [...(byGroup.get(a.group) || []), a]);
	const sections = [];
	for (const [slug, entries] of [...byGroup.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
		const meta = groups[slug] || {};
		sections.push(`## ${slug}${meta.name ? ` — ${cell(meta.name)}` : ''} (${entries.length} document${entries.length === 1 ? '' : 's'})`, '');
		sections.push('| Id | Date | Title | Kind | Status | Decisions | Summary |', '|---|---|---|---|---|---|---|');
		for (const a of [...entries].sort((x, y) => y.data.date.localeCompare(x.data.date) || y.data.id.localeCompare(x.data.id))) {
			const date = a.data.date_confidence === 'low' ? `${a.data.date}?` : a.data.date;
			sections.push(`| ${a.data.id} | ${date} | [${cell(a.data.title)}](${slug}/${path.basename(a.file)}) | ${a.data.kind} | ${stateOf(a)} | ${a.data.decisions.length} | ${cell(a.data.summary)} |`);
		}
		sections.push('');
	}
	fs.writeFileSync(
		path.join(p.archive, 'INDEX.md'),
		[
			`# Archive — ${scopeLabel(project)}`,
			GENERATED_MARK,
			'',
			`Old research and specs, digested: ${archive.length} document${archive.length === 1 ? '' : 's'} in ${byGroup.size} group${byGroup.size === 1 ? '' : 's'}. ` +
				'Each entry is a digest; the original and its extracted text sit in the group\'s sources/ folder. ' +
				'"Superseded" means a newer version exists in the same group. A date ending in "?" is a low-confidence guess. ' +
				'Decisions found here were never triaged: see the legacy section of ../memory/DECISIONS.md.',
			'',
			...sections,
		].join('\n'),
	);
}

function decisionRows(handoffs) {
	const rows = [];
	for (const h of [...handoffs].reverse()) h.data.decisions.forEach((d, i) => rows.push(`| ${h.data.id} d${i + 1} | ${h.data.date} | ${h.data.topics.join(', ')} | ${cell(d)} | ${stateOf(h)} |`));
	return rows;
}

function legacyRows(archive) {
	const rows = [];
	for (const a of [...archive].sort((x, y) => y.data.date.localeCompare(x.data.date))) {
		a.data.decisions.forEach((d, i) => rows.push(`| ${a.data.id} d${i + 1} | ${a.data.date} | ${a.group} | ${a.data.topics.join(', ')} | ${cell(d)} | ${stateOf(a, 'legacy')} |`));
	}
	return rows;
}

const LEGACY_NOTE =
	'They were made before the ledger existed and were never reviewed by the user in a run: treat them as "what we thought then", ' +
	'surface them as questions, never as settled policy. A hand-off decision on the same subject always wins.';

function decisionTables(handoffs, archive) {
	const rows = decisionRows(handoffs);
	const legacy = legacyRows(archive);
	return {
		rows,
		legacy,
		lines: [
			'| Ref | Date | Topics | Decision | State |',
			'|---|---|---|---|---|',
			...rows,
			'',
			`**Legacy decisions (from the archive, never triaged):** ${legacy.length}. ${LEGACY_NOTE}`,
			'',
			'| Ref | Date | Group | Topics | Decision | State |',
			'|---|---|---|---|---|---|',
			...legacy,
			'',
		],
	};
}

function writeDecisions(p, handoffs, archive, project) {
	const t = decisionTables(handoffs, archive);
	fs.mkdirSync(p.memory, { recursive: true });
	fs.writeFileSync(
		path.join(p.memory, 'DECISIONS.md'),
		[
			`# Decisions — ${scopeLabel(project)}`,
			GENERATED_MARK,
			'',
			`Decisions: ${t.rows.length}, from every hand-off header, newest first. "Superseded" rows are history, not current policy.`,
			'',
			...t.lines,
		].join('\n'),
	);
	return { decisions: t.rows.length, legacyDecisions: t.legacy.length };
}

function writeMemoryIndex(p, memory, project) {
	const rows = memory
		.sort((a, b) => a.kind.localeCompare(b.kind) || b.date.localeCompare(a.date))
		.map((m) => `| ${m.kind} | ${m.date} | [${cell(m.name)}](${m.kind}/${path.basename(m.file)}) | ${m.topics.join(', ')} | ${m.source} | ${cell(m.body.split('\n')[0]).slice(0, 120)} |`);
	fs.mkdirSync(p.memory, { recursive: true });
	fs.writeFileSync(
		path.join(p.memory, 'INDEX.md'),
		[
			project ? `# Memory — project ${project.name} (${project.slug})` : '# Memory — global',
			GENERATED_MARK,
			'',
			project
				? `Project memory files: ${memory.length}: facts (stable facts about this project) and lessons (what failed here and why). Preferences are global: see ../../../memory/INDEX.md.`
				: `Global memory files: ${memory.length}. Three nodes: preferences (how the user wants things done), facts (stable company facts), lessons (what failed and why). Decisions live in DECISIONS.md and in each project.`,
			'',
			'| Node | Date | Name | Topics | Source | First line |',
			'|---|---|---|---|---|---|',
			...rows,
			'',
		].join('\n'),
	);
}

function lastActivity(handoffs, archive) {
	return [...handoffs.map((h) => h.data.date), ...archive.map((a) => String(a.data.added || ''))].filter(Boolean).sort().pop() || '';
}

function writeProjectsIndex(root, summaries, legacy) {
	const rows = summaries.map(
		(s) =>
			`| ${s.id} | [${cell(s.name)}](projects/${s.slug}/handoffs/INDEX.md) | \`${s.slug}\` | ${s.status} | ${s.handoffs} | ${s.decisions} | ${s.archive} | ${s.lastActivity || '—'} | ${cell(s.description)} |`,
	);
	const legacyLine = legacy.any
		? `\n**Not yet in a project:** ${legacy.runs} run(s), ${legacy.handoffs} hand-off(s), ${legacy.archiveGroups} archive group(s) at the root; run \`/ledger run\` or \`/ledger setup\` to file them into a project.\n`
		: '';
	fs.writeFileSync(
		path.join(root, 'PROJECTS.md'),
		[
			'# Projects',
			GENERATED_MARK,
			'',
			`Projects: ${summaries.length}. Each has its own runs/, handoffs/ (with INDEX.md), archive/ (with INDEX.md) and memory/DECISIONS.md under projects/<slug>/. ` +
				'memory/DECISIONS.md at the root rolls every project up.',
			legacyLine,
			'| Id | Project | Slug | Status | Hand-offs | Decisions | Archived | Last activity | About |',
			'|---|---|---|---|---|---|---|---|---|',
			...rows,
			'',
		].join('\n'),
	);
}

function writeRootDecisions(root, perProject, legacy) {
	const sections = [];
	for (const { project, handoffs, archive } of perProject) {
		const t = decisionTables(handoffs, archive);
		sections.push(`## ${project ? `${project.name} (${project.slug})` : 'Not yet in a project'} — ${t.rows.length} decision${t.rows.length === 1 ? '' : 's'}, ${t.legacy.length} legacy`, '', ...t.lines);
	}
	const p = paths(root);
	fs.mkdirSync(p.globalMemory, { recursive: true });
	fs.writeFileSync(
		path.join(p.globalMemory, 'DECISIONS.md'),
		[
			'# Decisions — all projects',
			GENERATED_MARK,
			'',
			'Roll-up of every project\'s memory/DECISIONS.md, one section per project. A spec is checked only against its own project; this file is for reading across projects.',
			'',
			...(legacy.any ? [] : []),
			...sections,
		].join('\n'),
	);
}

export function writeIndexes(root) {
	const projects = listProjects(root);
	const summaries = [];
	const perProject = [];
	let totals = { handoffs: 0, archive: 0, decisions: 0, legacyDecisions: 0 };
	for (const project of projects) {
		const p = paths(root, project.slug);
		const handoffs = loadHandoffs(root, project.slug);
		const archive = loadArchive(root, project.slug);
		writeHandoffIndex(p, handoffs, project);
		writeArchiveIndex(p, archive, readGroups(root, project.slug), project);
		const c = writeDecisions(p, handoffs, archive, project);
		writeMemoryIndex(p, loadMemory(root, project.slug).filter((m) => m.scope === 'project'), project);
		summaries.push({ ...project, handoffs: handoffs.length, archive: archive.length, ...c, lastActivity: lastActivity(handoffs, archive) });
		perProject.push({ project, handoffs, archive });
		totals = { handoffs: totals.handoffs + handoffs.length, archive: totals.archive + archive.length, decisions: totals.decisions + c.decisions, legacyDecisions: totals.legacyDecisions + c.legacyDecisions };
	}
	const legacy = legacyContent(root);
	const rootPaths = paths(root);
	const legacyHandoffs = loadHandoffs(root, null);
	const legacyArchive = loadArchive(root, null);
	if (legacyHandoffs.length) writeHandoffIndex(rootPaths, legacyHandoffs, null);
	if (legacyArchive.length) writeArchiveIndex(rootPaths, legacyArchive, readGroups(root, null), null);
	if (legacyHandoffs.length || legacyArchive.length) perProject.push({ project: null, handoffs: legacyHandoffs, archive: legacyArchive });
	writeProjectsIndex(root, summaries, legacy);
	writeRootDecisions(root, perProject, legacy);
	writeMemoryIndex(rootPaths, loadMemory(root, null), null);
	return { projects: projects.length, ...totals, memory: loadMemory(root, null).length, legacy };
}

// ---------------------------------------------------------------- selection

/**
 * The words of `text` worth matching, most frequent first: at most `limit` words and, counted
 * apart, at most `cjkLimit` CJK bigrams, so the many bigrams of a Chinese text never push out its
 * other words (in a translation, those are what match the English original). When the words
 * overflow `limit`, a bigram must also be as frequent as the last word kept (5 times at most), so a
 * short Chinese quotation cannot outweigh an English document's subject. `exact` (find) also keeps
 * ids, dates, amounts, versions, numbers of three or more digits and lone CJK characters: noise in a
 * whole document, but exactly what a search for "1234.5678" or "H-017" means.
 */
export function keywords(text, { exact = false, limit = Infinity, cjkLimit = limit } = {}) {
	const word = (w) => w.length >= 3 && !STOP.has(w) && (exact || !/^\d+$/.test(w));
	const lower = fold(text);
	const words = [];
	for (const m of lower.matchAll(exact ? TOKEN : TOKEN_LOOSE)) {
		const [, run, whole, plain] = m;
		if (run) {
			const chars = [...run];
			const alone = !/[\p{L}\p{N}]/u.test(lower[m.index - 1] || '') && !/[\p{L}\p{N}]/u.test(lower[m.index + run.length] || '');
			if (chars.length === 1 && exact && alone && !CJK_STOP_CHARS.has(run)) words.push(run);
			for (let i = 0; i + 1 < chars.length; i++) {
				const pair = chars[i] + chars[i + 1];
				const stops = CJK_STOP_CHARS.has(chars[i]) + CJK_STOP_CHARS.has(chars[i + 1]);
				if (!CJK_STOP.has(pair) && (stops === 0 || (stops === 1 && (exact || chars.length === 2)))) words.push(pair);
			}
		} else if (whole) words.push(whole);
		else if (word(plain)) words.push(plain);
	}
	const freq = new Map();
	for (const w of words) freq.set(w, (freq.get(w) || 0) + 1);
	const sorted = [...freq.entries()].sort((a, b) => b[1] - a[1]);
	const others = sorted.filter(([w]) => !CJK_START.test(w));
	const floor = limit > 0 && others.length > limit ? Math.min(others[limit - 1][1], 5) : 0;
	const left = { cjk: cjkLimit, other: limit };
	return sorted.filter(([w, n]) => (CJK_START.test(w) ? n >= floor && left.cjk-- > 0 : left.other-- > 0)).map(([w]) => w);
}

/** True for a CJK keyword (a bigram or a lone character). */
export const isCjkWord = (w) => CJK_START.test(w);

const escapeRe = (w) => w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const patterns = new Map();

/**
 * Where folded `text` holds `w`, or -1: an id only as a whole id (A-100 is not in A-1004); with
 * `wordStart`, a non-CJK word only at the start of a word ("vat" is not in "private"); anything
 * else as a substring.
 */
function locate(text, w, wordStart = false) {
	const whole = ID_WORD.test(w);
	if (!whole && !(wordStart && !CJK_START.test(w))) return text.indexOf(w);
	const key = `${whole ? 'id' : 'start'}:${w}`;
	if (!patterns.has(key)) patterns.set(key, new RegExp(`(?<!${NB})${escapeRe(w)}${whole ? `(?!${NB})` : ''}`, 'u'));
	const m = patterns.get(key).exec(text);
	return m ? m.index : -1;
}

export function scoreText(words, fields, { wordStart = false } = {}) {
	let s = 0;
	for (const [text, weight] of fields) {
		const lower = fold(text);
		for (const w of words) if (locate(lower, w, wordStart) >= 0) s += weight;
	}
	return s;
}

function headerFields(e) {
	return [
		[e.data.topics.join(' '), 4],
		[e.data.title, 3],
		[e.data.summary, 2],
		[e.data.decisions.join(' '), 2],
		[e.body, 0.25],
	];
}

function decisionRefs(e) {
	return e.data.decisions.map((d, i) => ({ ref: `${e.data.id} d${i + 1}`, text: d, active: e.data.status !== 'superseded' }));
}

function rank(words, entries, max) {
	return entries
		.map((e) => ({ e, score: scoreText(words, headerFields(e)) }))
		.filter((x) => x.score >= 3)
		.sort((a, b) => b.score - a.score)
		.slice(0, max);
}

/**
 * What a spec (or a check) should read for `text`, strictly inside one project: every
 * preference, matching facts and lessons (global and project), matching hand-offs (full body
 * only when few), their active decisions, and matching archive digests (canonical versions only).
 */
export function selectContext(root, text, { project = null, maxHandoffs = 8, maxArchive = 6, fullTextLimit = 3 } = {}) {
	const words = keywords(text, { limit: 40 });
	const allHandoffs = loadHandoffs(root, project);
	const allArchive = loadArchive(root, project);
	const handoffs = rank(words, allHandoffs, maxHandoffs);
	const archive = rank(words, allArchive.filter((a) => a.data.status !== 'superseded'), maxArchive);
	const includeBody = handoffs.length <= fullTextLimit;
	const memory = loadMemory(root, project).filter(
		(m) => m.kind === 'preferences' || scoreText(words, [[m.topics.join(' '), 4], [m.name, 3], [m.body, 1]]) >= 3,
	);
	return {
		project,
		keywords: words,
		handoffs: handoffs.map(({ e: h, score: s }) => ({
			id: h.data.id,
			file: h.relFile,
			title: h.data.title,
			date: h.data.date,
			topics: h.data.topics,
			status: h.data.status,
			superseded_by: h.data.superseded_by,
			summary: h.data.summary,
			decisions: decisionRefs(h),
			score: s,
			body: includeBody ? h.body.trim() : undefined,
		})),
		archive: archive.map(({ e: a, score: s }) => ({
			id: a.data.id,
			file: a.relFile,
			title: a.data.title,
			kind: a.data.kind,
			date: a.data.date,
			date_confidence: a.data.date_confidence,
			group: a.group,
			topics: a.data.topics,
			summary: a.data.summary,
			legacyDecisions: decisionRefs(a).map(({ ref, text: t }) => ({ ref, text: t, triaged: false })),
			score: s,
		})),
		memory: memory.map((m) => ({ kind: m.kind, scope: m.scope, file: m.relFile, name: m.name, topics: m.topics, date: m.date, body: m.body })),
		allTopics: [...new Set([...allHandoffs, ...allArchive].flatMap((e) => e.data.topics))].sort(),
		fullTextIncluded: includeBody,
	};
}

function snippet(text, words, { wordStart = false } = {}, width = 220) {
	const norm = String(text ?? '').normalize('NFKC');
	const lower = norm.toLowerCase();
	let at = -1;
	for (const w of words) {
		at = locate(lower, w, wordStart);
		if (at >= 0) break;
	}
	if (at < 0) return '';
	const start = Math.max(0, at - Math.floor(width / 3));
	return `${start ? '…' : ''}${norm.slice(start, start + width).replace(/\s+/g, ' ').trim()}…`;
}

// A text original (.md, .txt, .csv) is its own text: the archive keeps no .txt copy beside it.
const TEXT_SOURCE = /\.(md|markdown|txt|csv)$/i;
// PDF extraction breaks lines inside Chinese words (数据\n库): join CJK across a line break.
const CJK_LINE_BREAK = new RegExp(`(?<=[${CJK}])[ \\t]*\\r?\\n[ \\t]*(?=[${CJK}])`, 'gu');

/** An entry's source text, or null when it has none or it cannot be read (then the digest alone is scored). */
function sourceText(a) {
	const dir = path.dirname(a.file);
	const file = a.data.source_text ? path.join(dir, a.data.source_text) : TEXT_SOURCE.test(a.data.source) ? path.join(dir, a.data.source) : null;
	if (!file) return null;
	try {
		return fs.readFileSync(file, 'utf8').replace(CJK_LINE_BREAK, '');
	} catch {
		return null;
	}
}

/** A Chinese date as an ISO date: 2026年3月15日 → 2026-03-15, 2026年3月 → 2026-03; anything else unchanged. */
function isoDate(w) {
	const m = /^(\d{4})年(\d{1,2})月(?:(\d{1,2})[日号])?$/.exec(w);
	return m ? `${m[1]}-${m[2].padStart(2, '0')}${m[3] ? `-${m[3].padStart(2, '0')}` : ''}` : w;
}

/** 5 when a search word is the entry's own id ("find H-017") or its date or month ("find 2026-03", "2026年3月"), else 0. */
function ownScore(words, e) {
	const id = String(e.data.id).toLowerCase();
	const date = String(e.data.date || '');
	return words.includes(id) || words.map(isoDate).some((w) => /^\d{4}-\d{2}(-\d{2})?$/.test(w) && date.startsWith(w)) ? 5 : 0;
}

/**
 * One search term (a word, an id, or one unbroken Chinese phrase): every entry that holds it (for
 * a Chinese phrase, all its bigrams; for a word, at the start of a word), best first. With several
 * terms an entry needs a minimum score: one term in its title, topics, summary or decisions is
 * enough, while matches only in its text need several.
 */
function scopeMatches(root, project, words, single = false) {
	const o = { wordStart: single };
	const enough = (s, min, texts) => (single ? words.every((w) => texts.some((t) => locate(fold(t), w, true) >= 0)) : s >= min);
	const hits = [];
	for (const h of loadHandoffs(root, project)) {
		const own = ownScore(words, h);
		const s = own + scoreText(words, headerFields(h), o) + scoreText(words, [[h.body, 0.5]], o);
		if (own || enough(s, 2, headerFields(h).map(([t]) => t)))
			hits.push({ kind: 'handoff', project, id: h.data.id, file: h.relFile, title: h.data.title, date: h.data.date, status: h.data.status, score: s, snippet: snippet(h.body, words, o) || h.data.summary });
	}
	for (const a of loadArchive(root, project)) {
		const own = ownScore(words, a);
		let s = own + scoreText(words, headerFields(a), o) + scoreText(words, [[a.body, 0.5]], o);
		let where = a.body;
		const full = sourceText(a);
		if (full != null) {
			const inSource = scoreText(words, [[full, 1]], o);
			if (inSource > 0 && s < 2) where = full;
			s += Math.min(inSource, 3);
		}
		if (own || enough(s, 2, [...headerFields(a).map(([t]) => t), full || '']))
			hits.push({ kind: 'archive', project, id: a.data.id, file: a.relFile, title: a.data.title, date: a.data.date, group: a.group, status: a.data.status, superseded_by: a.data.superseded_by, source: a.data.source ? `${path.dirname(a.relFile)}/${a.data.source}` : '', score: s, snippet: snippet(where, words, o) || (full ? snippet(full, words, o) : '') || a.data.summary });
	}
	for (const m of loadMemory(root, project).filter((m) => project ? m.scope === 'project' : true)) {
		const fields = [[m.topics.join(' '), 4], [m.name, 3], [m.body, 1]];
		const s = scoreText(words, fields, o);
		if (enough(s, 3, fields.map(([t]) => t))) hits.push({ kind: m.kind, project: m.scope === 'global' ? null : project, id: '', file: m.relFile, title: m.name, date: m.date, score: s, snippet: snippet(m.body, words, o) });
	}
	return hits;
}

/**
 * Full-text search for "where did we write about X". Scoped to one project (hand-offs, digests,
 * extracted sources, project memory) plus global memory, with per-project hit counts for the
 * rest ("elsewhere"); or every project when `all` is set, each hit labelled with its project.
 * `matches` holds the best `max`; `total` counts them all.
 */
export function searchAll(root, text, { project = null, all = false, max = 12, exact = false } = {}) {
	const words = keywords(text, { exact, limit: 20 });
	const scope = all ? 'all' : project;
	if (!words.length) return { keywords: [], scope, total: 0, matches: [], elsewhere: {}, note: 'Every word is too short (under three characters) or too common to search.' };
	// One term when exactly one piece of the query yields keywords: a Chinese phrase is one term, not its bigrams.
	const single = [...fold(text).matchAll(exact ? TOKEN : TOKEN_LOOSE)].filter((m) => keywords(m[0], { exact }).length).length === 1;
	const projects = listProjects(root).map((p) => p.slug);
	const legacy = legacyContent(root).any;
	const scopes = all ? [...projects, ...(legacy ? [null] : [])] : [project];
	const matches = scopes.flatMap((s) => scopeMatches(root, s, words, single));
	if (!all) {
		const o = { wordStart: single };
		const globalMem = loadMemory(root, null)
			.map((m) => ({ m, fields: [[m.topics.join(' '), 4], [m.name, 3], [m.body, 1]] }))
			.map((x) => ({ ...x, s: scoreText(words, x.fields, o) }))
			.filter(({ s, fields }) => (single ? s > 0 && words.every((w) => fields.some(([t]) => locate(fold(t), w, true) >= 0)) : s >= 3))
			.map(({ m, s }) => ({ kind: m.kind, project: null, id: '', file: m.relFile, title: m.name, date: m.date, score: s, snippet: snippet(m.body, words, o) }));
		matches.push(...globalMem);
	}
	const elsewhere = {};
	if (!all) for (const s of [...projects, ...(legacy ? [null] : [])].filter((s) => s !== project)) {
		const n = scopeMatches(root, s, words, single).filter((h) => h.kind === 'handoff' || h.kind === 'archive').length;
		if (n) elsewhere[s || '(not yet in a project)'] = n;
	}
	const sorted = matches.sort((a, b) => b.score - a.score);
	return { keywords: words, scope, total: sorted.length, matches: sorted.slice(0, max), elsewhere };
}
